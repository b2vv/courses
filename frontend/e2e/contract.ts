// Не тест-файл: Playwright забороняє тестам імпортувати одне одного, тож спільна операція
// живе тут, як `auth.ts` і `playback-profile.ts`.
//
// B-6 (`work/backlog.md`): браузерні тести читають відповіді як `unknown` і звужують їх
// рукописними асершенами, тож ім'я поля не звіряється ні з чим. `Reflect.get(body, 'position')`
// з описки віддає `undefined`, і свита падає повідомленням «відповідь неповна» або тихо
// повертає `null` — тобто звітує про поведінку продукту там, де помилилась сама. Рівно ця
// описка була найімовірнішим сценарієм у T8 (`positionSeconds` у heartbeat проти `position` у
// читальній моделі), і спіймав її рецензент, а не інструмент.
//
// `contractField` бере ключ, який мусить існувати в **генерованій** моделі, тож описка стає
// помилкою `typecheck` до будь-якого прогону. Моделі походять з `openapi.yaml`, а `make
// check-generated` стереже їхню відповідність документу.
//
// Чого воно НЕ ловить: розходження документа з реальним сервером. Якщо `openapi.yaml` бреше,
// застосунок і тести збрешуть однаково; це закривають контрактні тести на HTTP, яких
// `AGENTS.md` вимагає окремо. Тому анотуються **лише** читання, форму яких визначає контракт;
// зонди інструментації (`__o1CurrentTimeWrites`, `__mediaProgressValues`, `__TSR_ROUTER__`)
// лишаються на сирому `Reflect.get` — там генерованої моделі немає, і вдавати її шкідливо.
export function contractField<Model>(record: object, key: keyof Model & string): unknown {
  return Reflect.get(record, key);
}
